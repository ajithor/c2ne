package main

import (
	"fmt"
	"encoding/binary"
)


type WavHeader struct {
	SampleRate    uint32
	Channels      uint16
	BitsPerSample uint16
	ByteRate      uint32 // = SampleRate * Channels * BitsPerSample/8
	BlockAlign    uint16 // = Channels * BitsPerSample/8
	DataStart     int64  // byte offset where audio data begins
	DataSize      uint32 // size of audio data in bytes
}

func parseWavHeader(data []byte) (*WavHeader, error) { //generated by AI
	var h WavHeader
	if len(data) < 44 || string(data[0:4]) != "RIFF" || string(data[8:12]) != "WAVE" {
		return &h, fmt.Errorf("not a valid WAV file")
	}

	// Walk chunks after the 12-byte RIFF header, since 'fmt' and 'data'
	// aren't always at fixed offsets (some files have extra chunks, like LIST/INFO)
	offset := 12
	for offset+8 <= len(data) {
		chunkID := string(data[offset : offset+4])
		chunkSize := binary.LittleEndian.Uint32(data[offset+4 : offset+8])
		body := offset + 8

		switch chunkID {
		case "fmt ":
			h.Channels = binary.LittleEndian.Uint16(data[body+2 : body+4])
			h.SampleRate = binary.LittleEndian.Uint32(data[body+4 : body+8])
			h.ByteRate = binary.LittleEndian.Uint32(data[body+8 : body+12])
			h.BlockAlign = binary.LittleEndian.Uint16(data[body+12 : body+14])
			h.BitsPerSample = binary.LittleEndian.Uint16(data[body+14 : body+16])
		case "data":
			h.DataStart = int64(body)
			h.DataSize = chunkSize
		}

		offset = body + int(chunkSize)
		if chunkSize%2 == 1 { // chunks are word-aligned, pad byte if odd size
			offset++
		}
	}

	if h.DataStart == 0 {
		return &h, fmt.Errorf("no data chunk found")
	}
	return &h, nil
}